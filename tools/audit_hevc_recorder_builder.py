#!/usr/bin/env python3
"""Audit HEVC recorder parameter *builders* in private Ghidra C excerpts.

This performs no firmware disassembly or USB interaction itself. Feed it the
PRIVATE, locally decompiled C text of the identified recorder functions,
generated by ghidra_scripts/TraceX6Function.java. These exact model/version
addresses apply only to X-T3 5.11, X-T4 2.12 and X-S10 3.11; do not treat
them as addresses in the user's older X-S10 2.10 camera.

Important interpretation:
 input[2] is a Q16.16 FPS value, supported by six common constants.
 input[3] differs in the three analyzed recorder builders (XT3 and XT4
 can assign 1 or 3; XS10 was only observed assigning 3). Its meaning
 is NOT established as profile, bitdepth or a codec activation flag.
"""
import argparse
from pathlib import Path
import re
from typing import NamedTuple


class ModelParams(NamedTuple):
    param_struct: int
    driver_wrapper: int


MODELS = {
    "xt3": ModelParams(0x0246BF24, 0x01096B44),
    "xt4": ModelParams(0x028A5114, 0x011CAB08),
    "xs10": ModelParams(0x029459CC, 0x011F745C),
}


def decode_q16_fps(value: int):
    if not isinstance(value, int) or not 0 <= value <= 0xFFFFFFFF:
        raise ValueError("Invalid Q16.16 fps value")
    return value / 65536.0


def assignment_constants(source: str, address: int) -> list[int]:
    """Gather C assignments with literal RHS to a specific DWORD global."""
    pattern = re.compile(
        rf"(?:\b_DAT_|\bDAT_){address:08x}\s*=\s*"
        rf"(0x[0-9a-fA-F]+|[0-9]+)\s*;"
    )
    return [int(m.group(1), 0) for m in pattern.finditer(source)]


def audit_builder(source: str, model: str):
    """Verify the cross-section function call and two chosen input DWORDs."""
    if model not in MODELS:
        raise ValueError("Unknown fixed firmware model/version")
    base, wrapper = MODELS[model]
    # Decompiler labels a global struct with a non-prefixed DAT, but
    # individual fields may carry _DAT_ labels.
    invocation = re.search(
        rf"func_0x{wrapper:08x}\(&DAT_{base:08x},", source)
    if invocation is None:
        raise ValueError(f"{model} does not show verified HEVC wrapper call")
    fps_values = sorted(set(assignment_constants(source, base + 8)))
    type_values = sorted(set(assignment_constants(source, base + 12)))
    if not fps_values:
        raise ValueError("No constant Q16.16 FPS values found")
    if not type_values:
        raise ValueError("No input[3] literal values found")
    return {
        "model": model,
        "parameter_struct_address": f"0x{base:08x}",
        "wrapper_address": f"0x{wrapper:08x}",
        "input_2_q16_fps_raw": [f"0x{x:08x}" for x in fps_values],
        "input_2_fps_interpreted": [round(decode_q16_fps(x), 4)
                                    for x in fps_values],
        "input_3_values_observed": type_values,
        "input_3_meaning": "UNVERIFIED: NOT proven to be bit depth or profile",
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    for model in MODELS:
        p.add_argument("--" + model, type=Path, required=True,
                       help="Private Ghidra C excerpt for specified model")
    args = p.parse_args()
    for model in MODELS:
        text = getattr(args, model).read_text(encoding="utf-8")
        print(audit_builder(text, model))
    print("Q16.16 FPS and input[3] analysis is entirely offline; do not")
    print("patch the camera using these unvalidated parameter semantics.")


if __name__ == "__main__":
    main()
